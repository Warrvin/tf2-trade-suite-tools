/**
 * Локализация расширения — русский (по умолчанию) и английский.
 *
 * Архитектура нарочно простая, без сторонней i18n-библиотеки: язык — часть
 * тех же общих настроек (utils/settings.ts#TF2SuiteSettings.locale), а
 * каждый bilingual-текст — обычный объект `{ ru: T; en: T }`, выбираемый
 * функцией `t()` ниже. Не заводим отдельный файл-словарь на ВСЕ строки
 * сразу (как классический `messages.json`) — при таком большом количестве
 * независимых модулей это создало бы один непомерно разросшийся файл и
 * разрывало бы текст UI-строки с местом, где она используется (тот же
 * довод, что и у обильных doc-комментариев в каждом модуле — контекст
 * должен быть рядом с кодом). Вместо этого у каждого модуля/компонента,
 * которому нужен текст на двух языках, — свой маленький объект `MESSAGES`
 * прямо в том же файле, тип которого выводится через `LocalizedText`
 * ниже.
 *
 * Content-скрипты читают locale ОДИН РАЗ при построении интерфейса модуля
 * (как и `isFeatureEnabled` — см. существующий паттерн entrypoints/*),
 * но каждый entrypoint дополнительно перезапускает модуль (stop + start)
 * при смене locale вживую (через watchSettings), пока модуль включён —
 * иначе заявление "Изменения применяются сразу" в шапке страницы настроек
 * не выполнялось бы для смены языка. Vue-компоненты (options/popup)
 * реактивны сами по себе — там достаточно ref+watchSettings без
 * перезапуска чего-либо.
 */

export type Locale = 'ru' | 'en';

export const DEFAULT_LOCALE: Locale = 'ru';

export const LOCALE_LABELS: Record<Locale, string> = {
  ru: 'Русский',
  en: 'English',
};

/** Bilingual-значение любого типа — заголовок, описание, массив строк и т.п. */
export type LocalizedText<T = string> = Record<Locale, T>;

/** Выбирает нужный язык из bilingual-объекта — единственная точка, где это делается. */
export function t<T>(locale: Locale, text: LocalizedText<T>): T {
  return text[locale] ?? text[DEFAULT_LOCALE];
}
