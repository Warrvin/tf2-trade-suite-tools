/**
 * Кодировка типа объявления backpack.tf, которой обмениваются ДВА разных
 * модуля через query-параметр `listing_intent` в ссылке на трейд-оффер:
 * `bptf-listing-trade-params` (пишет — на странице backpack.tf) и
 * `auto-fill-from-listing` (читает — на странице оффера Steam). Вынесено в
 * отдельный файл, а не задублировано в обоих (требование 4), потому что
 * перепутать 0/1 местами легко (см. историю в README — направление платежа
 * зависит от того, кто в итоге является покупателем).
 *
 * 0 — объявление на ПОКУПКУ ("buy"): владелец объявления покупает, значит
 *     валюту в оффер добавляет ОН, а предмет для продажи посетитель ссылки
 *     выбирает сам (для таких объявлений backpack.tf не выдаёт `for_item` —
 *     нет одного конкретного ассета, продавец решает сам, какой отдать).
 * 1 — объявление на ПРОДАЖУ ("sell"): владелец объявления продаёт
 *     конкретный предмет (тот самый `for_item`), значит валюту добавляет
 *     посетитель ссылки.
 */
export type ListingIntent = 0 | 1;
